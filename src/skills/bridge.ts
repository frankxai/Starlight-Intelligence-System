/**
 * Starlight Cross-Marketplace Distribution Bridge
 *
 * Translates sovereign skills into standard distribution manifests for:
 *   1. Starlight Sovereign Marketplace (`starlightintelligence.org/marketplace`)
 *   2. Smithery Registry (`smithery.ai`)
 *   3. Glama MCP Registry (`glama.ai`)
 *   4. Cursor & Claude Directory (`.cursorrules`, `.claude/config.json`)
 *
 * Built on SIP — operational tier.
 */

import type { SkillDefinition, CrossMarketplaceManifests } from './types.js';

/**
 * Generates all multi-marketplace manifests from a single canonical SkillDefinition.
 */
export function generateCrossMarketplaceManifests(skill: SkillDefinition): CrossMarketplaceManifests {
  // 1. Starlight Native Catalog Registration
  const starlightCatalogEntry = {
    id: skill.id,
    name: skill.title,
    version: skill.version,
    kind: 'skill_pack',
    category: 'Community Extensions',
    description: skill.description,
    author: skill.author,
    pricingTier: skill.pricingTier,
    pricingMonthlyUsd: skill.pricingMonthlyUsd,
    tags: skill.tags,
    capabilities: skill.tools.length > 0 ? skill.tools : ['task:invoke'],
    permissions: skill.permissions,
    installCommand: `starlight pack install ${skill.id}${skill.permissions.length > 0 ? ' --ack-permissions' : ''}`,
    verifiedAttestation: true,
  };

  // 2. Smithery YAML Configuration
  const smitheryYaml = [
    `# smithery.yaml — Auto-generated by Starlight Ecosystem Bridge`,
    `name: ${skill.id}`,
    `version: "${skill.version}"`,
    `description: "${skill.description.replace(/"/g, '\\"')}"`,
    `command: node`,
    `args:`,
    `  - ./dist/mcp-server.js`,
    `tools:`,
    ...(skill.tools.length > 0 ? skill.tools.map((t) => `  - ${t}`) : [`  - default_tool`]),
    `pricing:`,
    `  tier: ${skill.pricingTier}`,
    `  monthlyUsd: ${skill.pricingMonthlyUsd || 0}`,
    `environmentVariables:`,
    `  - STARLIGHT_VAULT_PATH`,
  ].join('\n');

  // 3. Glama MCP JSON Descriptor
  const glamaJson = {
    $schema: 'https://glama.ai/mcp/schema.json',
    id: skill.id,
    name: skill.title,
    description: skill.description,
    version: skill.version,
    homepage: 'https://starlightintelligence.org/marketplace',
    repository: 'https://github.com/frankxai/Starlight-Intelligence-System',
    vendor: skill.author,
    license: skill.license,
    transport: {
      type: 'stdio',
      command: 'npx',
      args: ['-y', `@starlight-skills/${skill.id}`],
    },
    capabilities: {
      tools: skill.tools.reduce<Record<string, { description: string }>>((acc, tool) => {
        acc[tool] = { description: `Capability ${tool} provided by ${skill.title}` };
        return acc;
      }, {}),
    },
  };

  // 4. Cursor Rule Snippet
  const cursorRuleSnippet = [
    `# Starlight Sovereign Skill: ${skill.title} (${skill.id})`,
    `# Pricing Tier: ${skill.pricingTier.toUpperCase()}`,
    `Description: ${skill.description}`,
    `Required Permissions: ${skill.permissions.join(', ') || 'none (sandboxed)'}`,
    `\nInstructions:`,
    skill.instructions || 'Execute task adhering to strict quality and anti-slop guidelines.',
  ].join('\n');

  return {
    starlightCatalogEntry,
    smitheryYaml,
    glamaJson,
    cursorRuleSnippet,
  };
}
