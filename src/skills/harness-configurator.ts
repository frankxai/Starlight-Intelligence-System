/**
 * Starlight Intelligence System — Harness Configurator
 *
 * Translates universal SIP skill definitions into native configuration
 * files across 10 frontier developer harnesses.
 *
 * Built on SIP — Starlight Intelligence Protocol v1.1.1
 */

import type {
  HarnessTarget,
  HarnessConfig,
  HarnessOutputFile,
  SkillDefinition,
} from "./types.js";

export interface HarnessConfigOptions {
  projectName?: string;
  commandPrefix?: string;
  enableAllSkills?: boolean;
}

/**
 * Generates ready-to-write configuration files for any of the 10 supported developer harnesses.
 */
export function generateHarnessConfig(
  target: HarnessTarget,
  skills: SkillDefinition[],
  options: HarnessConfigOptions = {}
): HarnessConfig {
  const outputFiles: HarnessOutputFile[] = [];
  const notes: string[] = [];
  let validationStatus: "valid" | "warning" | "invalid" = "valid";

  if (skills.length === 0) {
    validationStatus = "warning";
    notes.push("No skills provided to harness generator. Emitted baseline config.");
  }

  const projectName = options.projectName ?? "starlight-agent";
  const prefix = options.commandPrefix ?? "";

  switch (target) {
    case "claude-code": {
      // 1. .claude/config.json
      const configObj = {
        name: projectName,
        version: "1.0.0",
        harness: "claude-code",
        enabledSkills: skills.map((s) => s.name),
        mcpServers: {
          starlight: {
            command: "starlight",
            args: ["mcp", "serve"],
          },
        },
      };
      outputFiles.push({
        relativePath: ".claude/config.json",
        format: "json",
        content: JSON.stringify(configObj, null, 2),
      });

      // 2. Command files for each skill
      for (const skill of skills) {
        const cmdName = `${prefix}${skill.name}.md`;
        const content = [
          `# /${skill.name}`,
          "",
          `> ${skill.description}`,
          "",
          "## Context Activation",
          skill.content ?? skill.description,
          "",
          "---",
          "*Generated by Starlight Harness Tuner (SIP v1.1.1)*",
        ].join("\n");

        outputFiles.push({
          relativePath: `.claude/commands/${cmdName}`,
          format: "markdown",
          content,
        });
      }
      notes.push(`Generated Claude Code config and ${skills.length} command files.`);
      break;
    }

    case "codex": {
      // .codex/skills.json
      const codexObj = {
        $schema: "https://schemas.openai.com/codex/skills.v1.json",
        skills: skills.map((s) => ({
          name: s.name,
          description: s.description,
          domain: s.domain,
          version: s.version,
          parameters: {
            type: "object",
            properties: {
              task: { type: "string", description: "The task context for this skill" },
            },
          },
          instructions: s.content ?? s.description,
        })),
      };
      outputFiles.push({
        relativePath: ".codex/skills.json",
        format: "json",
        content: JSON.stringify(codexObj, null, 2),
      });
      notes.push("Generated OpenAI Codex / AgentKit skills manifest.");
      break;
    }

    case "antigravity": {
      // .antigravity/skills.json + auto-hook markdown
      const agySkills = {
        name: projectName,
        target: "antigravity",
        skills: skills.map((s) => ({
          name: s.name,
          version: s.version,
          domain: s.domain,
          triggers: s.triggers ?? { keywords: [s.name] },
          permissions: s.permissions ?? { terminal: "read-write", filesystem: "read-write" },
        })),
      };
      outputFiles.push({
        relativePath: ".antigravity/skills.json",
        format: "json",
        content: JSON.stringify(agySkills, null, 2),
      });

      const hookContent = [
        "# Antigravity Skill Hooks",
        "",
        "Auto-activates workspace skills based on file patterns and keywords:",
        "",
        ...skills.map((s) => {
          const kws = s.triggers?.keywords?.join(", ") ?? s.name;
          return `- **${s.name}**: activates on \`[${kws}]\` — ${s.description}`;
        }),
      ].join("\n");

      outputFiles.push({
        relativePath: ".antigravity/skills-hooks.md",
        format: "markdown",
        content: hookContent,
      });
      notes.push("Generated Antigravity native skill and auto-hook definitions.");
      break;
    }

    case "cursor": {
      // .cursorrules and .cursor/rules/*.mdc
      const rules = [
        `# Cursor Rules for ${projectName}`,
        "",
        "## Active Skills & Behavioral Contracts",
        "",
        ...skills.map((s) => {
          return [
            `### Skill: ${s.name}`,
            `Domain: ${s.domain} (v${s.version})`,
            s.description,
            "",
            "Instructions:",
            s.content ?? s.description,
            "",
          ].join("\n");
        }),
      ].join("\n");

      outputFiles.push({
        relativePath: ".cursorrules",
        format: "markdown",
        content: rules,
      });
      notes.push("Generated .cursorrules file containing all active skills.");
      break;
    }

    case "grok": {
      const grokObj = {
        grokHarness: "1.0",
        project: projectName,
        skills: skills.map((s) => ({
          id: s.name,
          summary: s.description,
          triggers: s.triggers?.keywords ?? [s.name],
          instructions: s.content ?? s.description,
        })),
      };
      outputFiles.push({
        relativePath: "grok-skills.json",
        format: "json",
        content: JSON.stringify(grokObj, null, 2),
      });
      notes.push("Generated Grok CLI skills configuration.");
      break;
    }

    case "hermes": {
      const hermesObj = {
        version: "hermes-v1",
        toolplane: "starlight-hermes-mesh",
        skills: skills.map((s) => ({
          name: s.name,
          domain: s.domain,
          entrypoint: s.scripts?.[0]?.path ?? "inline",
          contextTokens: s.contextBudgetTokens ?? 1000,
        })),
      };
      outputFiles.push({
        relativePath: "hermes-skills.json",
        format: "json",
        content: JSON.stringify(hermesObj, null, 2),
      });
      notes.push("Generated Hermes Agent Runner configuration.");
      break;
    }

    case "gemini-cli": {
      const geminiObj = {
        geminiAgent: "1.0",
        skills: skills.map((s) => ({
          name: s.name,
          description: s.description,
          promptContract: s.content ?? s.description,
        })),
      };
      outputFiles.push({
        relativePath: "gemini-skills.json",
        format: "json",
        content: JSON.stringify(geminiObj, null, 2),
      });
      notes.push("Generated Gemini CLI prompt & skills manifest.");
      break;
    }

    case "opencode": {
      const opencodeObj = {
        opencodeVersion: "0.2.0",
        skills: skills.map((s) => ({
          id: s.name,
          description: s.description,
          path: `skills/${s.domain}/${s.name}.md`,
        })),
      };
      outputFiles.push({
        relativePath: "opencode.skills.json",
        format: "json",
        content: JSON.stringify(opencodeObj, null, 2),
      });
      notes.push("Generated OpenCode workspace configuration.");
      break;
    }

    case "kilo": {
      const kiloObj = {
        kiloEngine: "1.0",
        activeSkills: skills.map((s) => s.name),
      };
      outputFiles.push({
        relativePath: "kilo.config.json",
        format: "json",
        content: JSON.stringify(kiloObj, null, 2),
      });
      notes.push("Generated Kilo runner configuration.");
      break;
    }

    case "windsurf": {
      const windsurfRules = [
        `# Windsurf Cascade Rules — ${projectName}`,
        "",
        ...skills.map((s) => `## ${s.name}\n${s.description}\n`),
      ].join("\n");
      outputFiles.push({
        relativePath: ".windsurfrules",
        format: "markdown",
        content: windsurfRules,
      });
      notes.push("Generated .windsurfrules.");
      break;
    }

    default:
      validationStatus = "invalid";
      notes.push(`Unknown harness target: "${target}".`);
  }

  const instructionsSnippet = [
    `# Starlight Harness Configuration for ${target}`,
    `Skills: ${skills.length} active`,
    `Generated files: ${outputFiles.map((f) => f.relativePath).join(", ")}`,
  ].join("\n");

  return {
    target,
    outputFiles,
    activeSkillsCount: skills.length,
    instructionsSnippet,
    validationStatus,
    notes,
  };
}
