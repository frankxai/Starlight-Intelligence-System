#!/usr/bin/env node
/**
 * agents-md-project — project bands A and B of the agent contract into every repo.
 *
 * One way. SIS is the source; the repo is the destination. Nothing reads a repo's
 * AGENTS.md back into SIS. Implements docs/architecture/AGENTS-MD-CONTRACT.md.
 *
 *   ontology/agents-md/band-a.md    inherited — identical estate-wide
 *   ontology/company-registry.json  company, entity, brand register, accountable seat
 *   ontology/repo-tiers.json        tier and what it implies about installing
 *        |
 *        v
 *   <repo>/AGENTS.md    bands A + B, fenced. Band C is never touched.
 *
 * Band C is whatever lies outside the fences. The generator strips the fences,
 * keeps the remainder byte-for-byte, and re-emits A + B + C in that order.
 *
 * Usage:
 *   node scripts/agents-md-project.mjs --tree ..            write into sibling checkouts
 *   node scripts/agents-md-project.mjs --tree .. --check    verify only, non-zero if stale
 *   node scripts/agents-md-project.mjs --tree .. --repo X   one repo
 *   node scripts/agents-md-project.mjs --tree .. --tier T0,T1
 *   node scripts/agents-md-project.mjs --tree .. --init     also create absent AGENTS.md
 *
 * T3 is excluded unless named with --tier, because T3 is a consolidation proposal
 * awaiting Frank's call and gets nothing until then.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i !== -1 ? argv[i + 1] : null;
};
const CHECK_ONLY = argv.includes('--check');
const INIT = argv.includes('--init');
const TREE = flag('--tree');
const ONLY_REPO = flag('--repo');
const TIERS = (flag('--tier') || 'T0,T1,T2').split(',').map((t) => t.trim()).filter(Boolean);

const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const registry = read('ontology/company-registry.json');
const tiers = read('ontology/repo-tiers.json');
const BAND_A_SRC = 'ontology/agents-md/band-a.md';
const bandABody = readFileSync(join(ROOT, BAND_A_SRC), 'utf8').trimEnd();

const problems = [];
const fail = (msg) => problems.push({ severity: 'error', msg });
const warn = (msg) => problems.push({ severity: 'warn', msg });

// --------------------------------------------------------------------- fences
// The sha pins the body the generator wrote. A body that no longer hashes to its
// own declared sha was hand-edited inside the fence, which the contract forbids.
const BAND_VERSION = 1;
const sha12 = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

const fenceRe = (band) =>
  new RegExp(
    `[ \\t]*<!-- STARLIGHT:BAND-${band}:BEGIN v(\\d+) sha=([0-9a-f]+)[^>]*-->\\r?\\n` +
      `([\\s\\S]*?)` +
      `\\r?\\n[ \\t]*<!-- STARLIGHT:BAND-${band}:END -->[ \\t]*\\r?\\n?`,
    'g',
  );

// The blank lines around the body are load-bearing, not cosmetic: without them a
// markdown formatter reads the opening comment and the heading as one block, and
// the closing comment as a continuation of the final list item — which is exactly
// what Prettier reported against arcanea-ai-app. Keep them.
function wrap(band, body) {
  const b = body.trim();
  return (
    `<!-- STARLIGHT:BAND-${band}:BEGIN v${BAND_VERSION} sha=${sha12(b)} — generated by ` +
    `scripts/agents-md-project.mjs, do not hand-edit -->\n\n${b}\n\n` +
    `<!-- STARLIGHT:BAND-${band}:END -->\n`
  );
}

/** A markdown table Prettier will not want to reformat: cells padded to column width. */
function table(rows) {
  const w = rows[0].map((_, i) => Math.max(3, ...rows.map((r) => r[i].length)));
  const line = (cells) => `| ${cells.map((c, i) => c.padEnd(w[i])).join(' | ')} |`;
  return [line(rows[0].map(() => '')), `| ${w.map((n) => '-'.repeat(n)).join(' | ')} |`, ...rows.map(line)].join('\n');
}

/** Existing fenced bodies, and the file with every fence removed (= Band C). */
function split(existing) {
  const found = {};
  let rest = existing;
  for (const band of ['A', 'B']) {
    rest = rest.replace(fenceRe(band), (_m, _v, sha, body) => {
      found[band] = { sha, body };
      return '';
    });
  }
  return { found, bandC: rest };
}

// ------------------------------------------------------------------- indexes
const companyById = new Map(registry.companies.map((c) => [c.id, c]));
const entityById = new Map(registry.entities.map((e) => [e.id, e]));
const brandById = new Map(registry.brands.map((b) => [b.id, b]));
const tierDef = tiers.tiers;

// INV-7. A public projection never carries money, jurisdiction, or a credential.
// Same pattern as scripts/estate-graph.mjs, deliberately: one definition of the
// invariant, or the generator and the validator disagree about what a leak is.
// (A stricter local variant here fired on the T1 tier name "revenue surface".)
const FORBIDDEN = /\b(iban|swift|bic|api[_-]?key|secret|password|"amount"|current_cash|jurisdiction)\b/i;

function renderBandB(repo, company) {
  const entity = entityById.get(company.routes_through);
  const brands = (company.owns_brands || []).map((id) => brandById.get(id)).filter(Boolean);
  const tier = tierDef[repo.tier];
  const name = repo.id.replace(/^repo:/, '');

  const lines = [
    `## Company projection — ${company.name}`,
    '',
    'Generated from the SIS company registry. This section says who owns this repo and',
    'who answers for it. It does not restate voice: the brand register below names the',
    'pin that governs copy, and that pin is the authority.',
    '',
  ];
  const rows = [
    ['Repo', `\`${name}\``],
    ['Company', `${company.name} — _${company.stage}_`],
    ['Thesis', company.thesis],
    ['Routes through', entity ? `${entity.name} (${entity.role})` : '_unassigned_'],
    ['Accountable seat', `\`${company.accountable_exec_seat}\``],
    ['Tier', `**${repo.tier} — ${tier.name}** · install: ${tier.install}`],
  ];
  if (repo.deploys) rows.push(['Deploys', `\`${repo.deploys}\``]);
  lines.push(table(rows), '');

  if (brands.length) {
    lines.push('**Brand register**', '');
    for (const b of brands) {
      const pin = b.copy_pin ? `\`${b.copy_pin}\`` : '_no COPY.md pin registered yet_';
      lines.push(`- **${b.name}** — ${b.register}. Pin: ${pin}`);
    }
    lines.push('');
  }

  lines.push(
    `**Tier rule.** ${tier.rule}`,
    '',
    `**Escalation.** Decisions this repo cannot make alone go to \`${company.accountable_exec_seat}\`.`,
    'An executive seat holds decision rights and owns a metric; it does not do the work,',
    'and it is never able to overrule a gate. Anything irreversible goes to Frank.',
  );
  return lines.join('\n');
}

// ------------------------------------------------------------------ the work
const selected = tiers.repos.filter((r) => {
  if (!TIERS.includes(r.tier)) return false;
  if (ONLY_REPO && r.id !== ONLY_REPO && r.id !== `repo:${ONLY_REPO}`) return false;
  return true;
});

if (!TREE) {
  console.error('agents-md-project: --tree <dir> is required — the directory holding the sibling checkouts.');
  process.exit(2);
}
if (ONLY_REPO && !selected.length) {
  console.error(`agents-md-project: no repo matching "${ONLY_REPO}" in the selected tiers (${TIERS.join(',')}).`);
  process.exit(2);
}

const bandA = wrap('A', bandABody);
let written = 0;
let unchanged = 0;
let skipped = 0;
const stale = [];
const tampered = [];

for (const repo of selected) {
  const name = repo.id.replace(/^repo:/, '');
  const company = companyById.get(repo.company);
  if (!company) {
    fail(`${name}: company ${repo.company} is not in the registry`);
    continue;
  }

  const dir = join(TREE, name);
  const file = join(dir, 'AGENTS.md');
  if (!existsSync(dir)) {
    skipped++;
    continue; // not checked out in this tree; not a defect
  }

  const bandBBody = renderBandB(repo, company);
  const leak = `${bandABody}\n${bandBBody}`.match(FORBIDDEN);
  if (leak) {
    fail(`${name}: INV-7 — projection would leak "${leak[0]}" into a public repo. Not written.`);
    continue;
  }
  const bandB = wrap('B', bandBBody);

  const exists = existsSync(file);
  if (!exists && !INIT) {
    warn(`${name}: no AGENTS.md. Band C is hand-written per repo — write it first, or pass --init for a stub.`);
    skipped++;
    continue;
  }

  const existing = exists ? readFileSync(file, 'utf8') : '';
  const { found, bandC } = split(existing);

  // A body that does not hash to its own declared sha was edited inside the fence.
  for (const band of ['A', 'B']) {
    if (found[band] && sha12(found[band].body.trim()) !== found[band].sha) {
      tampered.push(`${name}: band ${band} was hand-edited inside the fence — regenerating discards that edit. Change it upstream in SIS.`);
    }
  }

  let tail = bandC.replace(/^\s*\n+/, '').trimEnd();
  if (!tail) {
    tail = [
      `# AGENTS.md — ${name}`,
      '',
      '## Repo-local — hand-written',
      '',
      '> **TODO.** This section is the only part a generator never writes, because no',
      '> generator can invent this repo\'s build commands, ports, or local gates.',
      '> Replace this block with: how to build, how to test, what breaks, and any',
      '> contract that exists only here.',
      '',
      '_Band C outranks the generated bands above on any conflict inside this repo._',
    ].join('\n');
  }

  const next = `${bandA}\n${bandB}\n${tail}\n`;

  if (existing === next) {
    unchanged++;
    continue;
  }
  if (CHECK_ONLY) {
    stale.push(exists ? `${name}: AGENTS.md is stale` : `${name}: AGENTS.md is missing`);
    continue;
  }
  writeFileSync(file, next);
  written++;
}

// -------------------------------------------------------------------- report
for (const t of tampered) warn(t);
for (const s of stale) fail(`${s} — run \`npm run agents:project\` and commit the result.`);

const errors = problems.filter((p) => p.severity === 'error');
const warns = problems.filter((p) => p.severity === 'warn');

console.log('agents-md-project', CHECK_ONLY ? '(check only)' : `→ ${TREE}/<repo>/AGENTS.md`);
console.log(`  band A: ${BAND_A_SRC} sha=${sha12(bandABody)}`);
console.log(`  tiers: ${TIERS.join(',')}  selected: ${selected.length}`);
console.log(`  ${CHECK_ONLY ? 'up to date' : 'written'}: ${CHECK_ONLY ? unchanged : written}   unchanged: ${unchanged}   skipped: ${skipped}`);
for (const p of warns) console.log(`  WARN  ${p.msg}`);
for (const p of errors) console.log(`  ERROR ${p.msg}`);
console.log(`  ${errors.length} error(s), ${warns.length} warning(s)`);
process.exit(errors.length ? 1 : 0);
