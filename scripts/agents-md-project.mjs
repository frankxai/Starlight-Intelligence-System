#!/usr/bin/env node
/**
 * agents-md-project — keep Band A of this repo's AGENTS.md identical to its source.
 *
 * Implements docs/architecture/AGENTS-MD-CONTRACT.md for this repository only.
 *
 *   docs/architecture/agents-md/band-a.md   authored once, never hand-copied
 *        |
 *        v
 *   AGENTS.md   Band A, fenced at the top. Band C (everything outside the
 *               fence) is hand-written and kept byte-for-byte.
 *
 * Check-only by default: it verifies and exits non-zero on drift, and never
 * writes. That is the mode npm test and CI run. Writing is a local, explicit act:
 *
 *   node scripts/agents-md-project.mjs              verify; non-zero if stale or hand-edited
 *   node scripts/agents-md-project.mjs --write      regenerate the fence in place
 *   node scripts/agents-md-project.mjs --file <p>   operate on another file (tests)
 *
 * Line endings are normalised before comparing and hashing, so a CRLF checkout
 * on Windows and an LF checkout in CI agree on what "up to date" means.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i !== -1 ? argv[i + 1] : null;
};
const WRITE = argv.includes('--write');
const FILE = flag('--file') ? resolve(flag('--file')) : join(ROOT, 'AGENTS.md');
const BAND_A_SRC = 'docs/architecture/agents-md/band-a.md';
const BAND_VERSION = 1;

const lf = (s) => s.replace(/\r\n/g, '\n');
const sha12 = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
const bandABody = lf(readFileSync(join(ROOT, BAND_A_SRC), 'utf8')).trim();

// Band A is identical wherever it lands, so it must never carry money,
// jurisdiction, or a credential. Checked before anything is written.
const FORBIDDEN = /\b(iban|swift|bic|api[_-]?key|secret|password|"amount"|current_cash|jurisdiction)\b/i;

const FENCE = new RegExp(
  `[ \\t]*<!-- STARLIGHT:BAND-A:BEGIN v(\\d+) sha=([0-9a-f]+)[^>]*-->\\n` +
    `([\\s\\S]*?)` +
    `\\n[ \\t]*<!-- STARLIGHT:BAND-A:END -->[ \\t]*\\n?`,
  'g',
);

// The blank lines around the body keep markdown formatters from merging the
// opening comment with the heading, or the closing comment with the last list item.
function wrap(body) {
  return (
    `<!-- STARLIGHT:BAND-A:BEGIN v${BAND_VERSION} sha=${sha12(body)} — generated by ` +
    `scripts/agents-md-project.mjs, do not hand-edit -->\n\n${body}\n\n` +
    `<!-- STARLIGHT:BAND-A:END -->\n`
  );
}

const errors = [];
const warnings = [];
const leak = bandABody.match(FORBIDDEN);
if (leak) errors.push(`${BAND_A_SRC}: Band A would carry "${leak[0]}" into a public file.`);
if (!existsSync(FILE)) errors.push(`${FILE}: missing. Band C is hand-written; create it first.`);

let status = 'FAILED';
if (!errors.length) {
  const existing = lf(readFileSync(FILE, 'utf8'));
  const fences = [];
  const bandC = existing.replace(FENCE, (_m, _v, sha, body) => {
    fences.push({ sha, body: body.trim() });
    return '';
  });
  if (fences.length > 1) errors.push(`${FILE}: ${fences.length} Band A fences; expected one.`);
  for (const f of fences) {
    if (sha12(f.body) !== f.sha) {
      (WRITE ? warnings : errors).push(
        `${FILE}: Band A was hand-edited inside the fence (body sha ${sha12(f.body)}, fence says ${f.sha}). ` +
          `Change ${BAND_A_SRC} instead, then run with --write.`,
      );
    }
  }
  // Band C keeps its bytes, minus a stray BOM and the blank lines the fence left behind.
  const tail = bandC.replace(/^\uFEFF/, '').replace(/^\s*\n+/, '').trimEnd();
  const next = `${wrap(bandABody)}\n${tail}\n`;

  if (existing === next) {
    status = 'up to date';
  } else if (WRITE) {
    writeFileSync(FILE, next);
    status = 'written';
  } else if (!errors.length) {
    errors.push(
      `${FILE}: Band A is ${fences.length ? 'stale' : 'missing'} against ${BAND_A_SRC}. ` +
        'Run `node scripts/agents-md-project.mjs --write` and commit the result.',
    );
  }
}

console.log(`agents-md-project ${WRITE ? '(write)' : '(check only)'}`);
console.log(`  band A: ${BAND_A_SRC} sha=${sha12(bandABody)}`);
console.log(`  target: ${FILE} — ${status}`);
for (const w of warnings) console.log(`  WARN  ${w} (discarded by --write)`);
for (const e of errors) console.log(`  ERROR ${e}`);
process.exit(errors.length ? 1 : 0);
