#!/usr/bin/env node
// Recovered from PR #325; v2 rejects malformed spans and preserves all unowned bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = 'docs/architecture/agents-md/band-a.md';
export const digest = text => createHash('sha256').update(text).digest('hex');
export const normalize = text => text.replace(/\r\n/g, '\n').trim();

export function ownedSpan(text, name) {
  if (!/^[A-Z-]+$/.test(name)) throw new Error('invalid marker name');
  const fragments = [...text.matchAll(new RegExp('<!--\\s*STARLIGHT\\s*:\\s*' + name + '\\s*:', 'g'))].length;
  if (!fragments) return null;
  const pattern = new RegExp('(?:^|(?<=^\\uFEFF))<!-- STARLIGHT:' + name + ':BEGIN v[12] sha=[0-9a-f]{12}(?: source=[0-9a-f]{40})?(?: — generated by scripts/agents-md-project\\.mjs, do not hand-edit)? -->\\r?\\n[\\s\\S]*?^<!-- STARLIGHT:' + name + ':END -->(?=\\r?$)', 'gm');
  const spans = [...text.matchAll(pattern)];
  if (fragments !== 2 || spans.length !== 1) throw new Error(name + ': duplicate, malformed or unbalanced markers');
  const match = spans[0];
  const inner = match[0].slice(match[0].indexOf('\n') + 1, match[0].lastIndexOf('<!--'));
  if (/<!--\s*STARLIGHT\s*:/.test(inner)) throw new Error(name + ': nested managed markers');
  return { start: match.index, end: match.index + match[0].length, text: match[0] };
}

export function project(text, body, { name = 'BAND-A', sourceRef = null, prepend = name === 'BAND-A' } = {}) {
  const span = ownedSpan(text, name); // Validate BEFORE computing any replacement.
  const normalized = normalize(body);
  if (!normalized) throw new Error('empty source');
  if (/<!--\s*STARLIGHT\s*:/.test(normalized)) throw new Error('source must not contain managed markers');
  if (sourceRef && !/^[0-9a-f]{40}$/.test(sourceRef)) throw new Error('sourceRef must be a full commit SHA');
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const provenance = sourceRef ? ' source=' + sourceRef : '';
  const block = [
    '<!-- STARLIGHT:' + name + ':BEGIN v2 sha=' + digest(normalized).slice(0, 12) + provenance + ' -->',
    '', normalized, '',
    '<!-- STARLIGHT:' + name + ':END -->',
  ].join('\n').replace(/\n/g, eol);
  let next;
  if (span) next = text.slice(0, span.start) + block + text.slice(span.end);
  else if (prepend) {
    const bom = text.startsWith('\uFEFF') ? '\uFEFF' : '';
    next = bom + block + eol + eol + text.slice(bom.length);
  } else next = text + (text.endsWith(eol + eol) ? '' : text.endsWith(eol) ? eol : eol + eol) + block + eol;
  return { next, changed: next !== text, sha256: digest(normalized), priorSpan: span };
}

export function readmeBody(sourceRef) {
  if (!/^[0-9a-f]{40}$/.test(sourceRef)) throw new Error('README requires a pinned source commit');
  return [
    '## Agent operating guidance',
    '',
    'Repository agents use the shared Starlight operating contract in `AGENTS.md` alongside local instructions.',
    'The contract asks agents to establish a useful outcome, select relevant skills, complete authorized work,',
    'verify current sources, refine the actual artifact, and report evidence and remaining gates.',
    'It covers human agency, privacy, rights, resource stewardship and bounded proactivity.',
    'Repository identity, brand, canon, build commands and release gates remain local.',
    '',
    '[Pinned contract](https://github.com/frankxai/Starlight-Intelligence-System/blob/' + sourceRef + '/' + SOURCE + ')',
    '· [Projection and verification](https://github.com/frankxai/Starlight-Intelligence-System/blob/' + sourceRef + '/docs/architecture/AGENTS-MD-CONTRACT.md)',
    '',
    'These files supply operating guidance. They do not activate an agent, grant tool permissions,',
    'schedule recurring work, certify compliance or prove a live capability.',
  ].join('\n');
}

export function soulBody(sourceRef) {
  if (!/^[0-9a-f]{40}$/.test(sourceRef)) throw new Error('SOUL requires a pinned source commit');
  return [
    '## Operating qualities',
    '',
    'Preserve the identity and invariants in this file. Apply the shared operating contract',
    'through `AGENTS.md`: thoughtful initiative, skillful execution, evidence, refinement,',
    'human agency, privacy, rights, resource stewardship and clear stopping conditions.',
    'Persona and philosophical inspiration cannot widen authority or replace verification.',
    '',
    'Source: https://github.com/frankxai/Starlight-Intelligence-System/blob/' + sourceRef + '/' + SOURCE,
    '',
    'This section is guidance; a compiler or host must explicitly load it before runtime use.',
  ].join('\n');
}

export function main(argv = process.argv.slice(2)) {
  const value = flag => { const index = argv.indexOf(flag); if (index < 0) return null; if (!argv[index + 1] || argv[index + 1].startsWith('--')) throw new Error(flag + ' needs a value'); return argv[index + 1]; };
  const allowed = new Set(['--file', '--source-ref', '--write', '--kind']);
  for (let i = 0; i < argv.length; i++) {
    if (!allowed.has(argv[i])) throw new Error('unknown argument: ' + argv[i]);
    if (argv[i] !== '--write') i++;
  }
  const file = resolve(value('--file') || resolve(ROOT, 'AGENTS.md'));
  const kind = value('--kind') || 'agent';
  const text = readFileSync(file, 'utf8');
  const sourceRef = value('--source-ref') || ownedSpan(text, (kind === 'agent' ? 'BAND-A' : 'OPERATING'))?.text.match(/ source=([0-9a-f]{40}) /)?.[1] || null;
  const source = readFileSync(resolve(ROOT, SOURCE), 'utf8');
  if (sourceRef) {
    if (!/^[0-9a-f]{40}$/.test(sourceRef)) throw new Error('source-ref must be a full commit SHA');
    const committed = execFileSync('git', ['show', sourceRef + ':' + SOURCE], { cwd: ROOT, encoding: 'utf8' });
    if (normalize(committed) !== normalize(source)) throw new Error('source-ref content differs from the working source');
  }
  if (/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|\b(?:ghp_|sk_live_)[A-Za-z0-9]{16,}/.test(source)) throw new Error('credential-shaped source rejected');
  let body, name, prepend;
  if (kind === 'agent') { body = source; name = 'BAND-A'; prepend = true; }
  else if (kind === 'readme') { body = readmeBody(sourceRef); name = 'OPERATING'; prepend = false; }
  else if (kind === 'soul') { body = soulBody(sourceRef); name = 'OPERATING'; prepend = false; }
  else throw new Error('unknown kind: ' + kind);
  const result = project(text, body, { name, prepend, sourceRef });
  if (result.changed && argv.includes('--write')) writeFileSync(file, result.next);
  console.log(JSON.stringify({ target: file, kind, sourceSha256: result.sha256, state: result.changed ? (argv.includes('--write') ? 'written' : 'drift') : 'up to date' }));
  return result.changed && !argv.includes('--write') ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(); } catch (error) { console.error(error.message); process.exitCode = 2; }
}
