#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const model = JSON.parse(readFileSync(join(root, "docs/graph-engineering/atlas/estate-graph.v1.json"), "utf8"));
const target = join(root, "site/src/lib/graph-atlas-data.generated.ts");
// Public authored reference architecture; never import an operator's private census.
for (const view of model.views) for (const node of view.nodes) {
  if (node.status === 'current') node.status = 'reference';
}
const source = `/* Generated by scripts/generate-graph-atlas.mjs. Public reference model only. */\nexport const graphAtlas = ${JSON.stringify(model, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) {
    console.error('Graph atlas output drifted; run npm run graph-atlas:generate.');
    process.exitCode = 1;
  } else console.log(JSON.stringify({ ok: true, mode: 'check' }));
} else {
  writeFileSync(target, source, "utf8");
  console.log(JSON.stringify({ ok: true, output: "site/src/lib/graph-atlas-data.generated.ts" }));
}
