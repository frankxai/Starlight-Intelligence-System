"""Benchmark enabled memory substrates against the user's actual corpus.

Privacy-first: everything runs locally. Test queries are generated by local LLM
only (Ollama or llama.cpp). Raw results contain entry IDs only, never content.
Aborts if policy_set=sovereign and any external import is detected.

Per references/benchmarking-protocol.md.

Usage:
  python benchmark_substrates.py [--substrate <name>] [--quick] [--testset <path>]

Outputs:
  memory/benchmarks/{date}.json           — raw per-query, per-substrate metrics
  memory/benchmarks/{date}-summary.md      — human-readable one-pager
  memory/benchmarks/RECOMMENDATIONS.md     — rolling best-per-use-case
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from statistics import median
from typing import Any

# All substrate adapters live under service/memory/. The actual implementations
# are TODO — the orchestrator skill defines the contract; this script discovers
# whatever adapters are registered.

SIS_ROOT = Path(__file__).resolve().parents[4]
BENCH_DIR = SIS_ROOT / "memory" / "benchmarks"


@dataclass
class QueryResult:
    substrate: str
    query: str
    expected_id: str
    hit: bool
    rank: int  # 1-based; 0 if miss
    latency_ms: float
    leaks: int


@dataclass
class SubstrateMetrics:
    substrate: str
    n: int = 0
    hits: int = 0
    latencies: list[float] = field(default_factory=list)
    leaks_total: int = 0

    @property
    def recall_at_5(self) -> float:
        return self.hits / self.n if self.n else 0.0

    @property
    def latency_p50(self) -> float:
        return median(self.latencies) if self.latencies else 0.0

    @property
    def latency_p95(self) -> float:
        if not self.latencies:
            return 0.0
        s = sorted(self.latencies)
        idx = int(len(s) * 0.95) - 1
        return s[max(0, idx)]


def load_test_set(path: Path) -> list[dict]:
    """Load (query, expected_id) pairs. Each line is JSON with {q, id}."""
    if not path.exists():
        print(f"[bench] test set missing: {path}", file=sys.stderr)
        print("[bench] generate via: python benchmark_substrates.py --regen-testset", file=sys.stderr)
        sys.exit(1)
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def discover_substrates() -> list[Any]:
    """Find enabled substrates from substrates.toml.

    The actual adapter classes live at service.memory.<substrate>_adapter and
    expose .retrieve(query, k=5) -> list[Hit] where Hit has .id and .score.

    Returns the list of adapter instances; empty if none configured (which means
    no benchmark to run — caller decides).
    """
    cfg_path = SIS_ROOT / "private" / "voice-operator" / "config" / "substrates.toml"
    if not cfg_path.exists():
        print(f"[bench] no substrates.toml at {cfg_path}", file=sys.stderr)
        return []

    try:
        import tomllib
        cfg = tomllib.loads(cfg_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[bench] config parse error: {e}", file=sys.stderr)
        return []

    adapters = []
    for name, sub in (cfg.get("substrates") or {}).items():
        if not sub.get("enabled"):
            continue
        # Adapters are loaded lazily — if module is missing, skip with warning.
        # The skill's substrate-matrix.md documents which adapters exist.
        module_name = f"service.memory.{name.replace('-', '_')}_adapter"
        try:
            mod = __import__(module_name, fromlist=["build_adapter"])
            adapters.append(mod.build_adapter(sub))
        except (ImportError, AttributeError) as e:
            print(f"[bench] adapter {name} unavailable ({e}) — skipping", file=sys.stderr)
            continue
    return adapters


def benchmark_substrate(adapter: Any, test_set: list[dict]) -> tuple[list[QueryResult], SubstrateMetrics]:
    """Run all test queries against one substrate."""
    name = getattr(adapter, "name", adapter.__class__.__name__)
    metrics = SubstrateMetrics(substrate=name)
    results: list[QueryResult] = []

    for entry in test_set:
        q = entry["q"]
        expected = entry["id"]
        t0 = time.perf_counter()
        try:
            hits = adapter.retrieve(q, k=5)
        except Exception as e:
            print(f"[bench] {name} retrieve error on q={q!r}: {e}", file=sys.stderr)
            hits = []
        latency = (time.perf_counter() - t0) * 1000

        rank = 0
        for i, h in enumerate(hits, start=1):
            if getattr(h, "id", None) == expected:
                rank = i
                break

        # Leak audit: scan retrieval bodies for PII not in the query scope.
        # Privacy Guardian impl is TODO; placeholder counts as 0 here.
        leaks = 0  # TODO: privacy_guardian.scan(hits, q)

        results.append(QueryResult(
            substrate=name, query=q, expected_id=expected,
            hit=(rank > 0 and rank <= 5), rank=rank,
            latency_ms=latency, leaks=leaks,
        ))
        metrics.n += 1
        if rank > 0 and rank <= 5:
            metrics.hits += 1
        metrics.latencies.append(latency)
        metrics.leaks_total += leaks

    return results, metrics


def write_outputs(date: str, all_results: list[QueryResult], all_metrics: list[SubstrateMetrics]) -> None:
    BENCH_DIR.mkdir(parents=True, exist_ok=True)

    raw_path = BENCH_DIR / f"{date}.json"
    raw_path.write_text(json.dumps({
        "date": date,
        "n_queries": all_metrics[0].n if all_metrics else 0,
        "substrates": [
            {
                "name": m.substrate,
                "recall_at_5": round(m.recall_at_5, 3),
                "latency_p50_ms": round(m.latency_p50, 1),
                "latency_p95_ms": round(m.latency_p95, 1),
                "leaks_total": m.leaks_total,
            }
            for m in all_metrics
        ],
        # NOTE: per privacy-hardening.md, raw results contain IDs only — NEVER
        # content. Looking up content requires a second pass against the vault.
        "results": [
            {
                "substrate": r.substrate,
                "query_id_hash": hash_query(r.query),
                "expected_id": r.expected_id,
                "hit": r.hit,
                "rank": r.rank,
                "latency_ms": round(r.latency_ms, 2),
                "leaks": r.leaks,
            }
            for r in all_results
        ],
    }, indent=2), encoding="utf-8")
    print(f"[bench] wrote {raw_path}")

    # Human-readable summary.
    summary_path = BENCH_DIR / f"{date}-summary.md"
    lines = [
        f"# Benchmark summary — {date}",
        "",
        "| Substrate | recall@5 | p50 (ms) | p95 (ms) | leaks |",
        "|---|---|---|---|---|",
    ]
    for m in sorted(all_metrics, key=lambda x: -x.recall_at_5):
        lines.append(
            f"| {m.substrate} | {m.recall_at_5:.2%} | {m.latency_p50:.0f} | {m.latency_p95:.0f} | {m.leaks_total} |"
        )
    lines.append("")
    lines.append("Privacy: all queries ran locally. No content shipped externally.")
    summary_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[bench] wrote {summary_path}")


def hash_query(q: str) -> str:
    """Stable short hash of a query so we can compare runs without storing literals."""
    import hashlib
    return hashlib.sha256(q.encode("utf-8")).hexdigest()[:12]


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--substrate", help="Run only one named substrate")
    p.add_argument("--quick", action="store_true", help="10 queries instead of 50")
    p.add_argument("--testset", type=Path, help="Override test set path")
    args = p.parse_args()

    date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    testset_path = args.testset or (BENCH_DIR / f"_testset_{date}.jsonl")

    if not testset_path.exists():
        # Fallback: any prior testset.
        prior = sorted(BENCH_DIR.glob("_testset_*.jsonl"))
        if prior:
            testset_path = prior[-1]
            print(f"[bench] using prior testset {testset_path.name}", file=sys.stderr)
        else:
            print("[bench] no testset; generate one via the orchestrator's testset-gen op", file=sys.stderr)
            return 1

    test_set = load_test_set(testset_path)
    if args.quick:
        test_set = test_set[:10]

    adapters = discover_substrates()
    if args.substrate:
        adapters = [a for a in adapters if getattr(a, "name", "") == args.substrate]
    if not adapters:
        print("[bench] no enabled substrates to benchmark", file=sys.stderr)
        return 1

    print(f"[bench] {len(adapters)} substrate(s), {len(test_set)} query/expected pair(s)")
    all_results: list[QueryResult] = []
    all_metrics: list[SubstrateMetrics] = []
    for a in adapters:
        results, metrics = benchmark_substrate(a, test_set)
        all_results.extend(results)
        all_metrics.append(metrics)

    write_outputs(date, all_results, all_metrics)
    return 0


if __name__ == "__main__":
    sys.exit(main())
